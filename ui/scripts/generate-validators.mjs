// Compiles the schemas in schema/ to src/lib/validators.gen.js, so the browser never builds a
// validator with Function() and the page needs no 'unsafe-eval' in its CSP. Run by `pnpm types`.
import { readFileSync, writeFileSync } from "node:fs";
import { Ajv2020 } from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";

const names = ["guidance", "index", "report"];
// NOTE: formats go unchecked, to keep ajv-formats out of the page. The exporter's tests check date-time.
const ajv = new Ajv2020({ allErrors: true, validateFormats: false, code: { source: true, esm: true } });
for (const name of names) {
  ajv.addSchema(JSON.parse(readFileSync(new URL(`../schema/${name}.schema.json`, import.meta.url), "utf8")), name);
}
// The one runtime helper standalone code needs, ajv's ucs2length (the length in code points), as a
// plain function: the module it comes from is CommonJS, which the bundle would have to convert.
const helper = 'require("ajv/dist/runtime/ucs2length").default';
const code = standaloneCode(ajv, Object.fromEntries(names.map((name) => [`${name}Validator`, name])));
const header =
  "/* eslint-disable */\n// Generated by scripts/generate-validators.mjs from schema/. Do not edit by hand.\n";
if (!code.includes(helper)) throw new Error("ajv's standalone code no longer requires ucs2length: update this script");
writeFileSync(
  new URL("../src/lib/validators.gen.js", import.meta.url),
  `${header}${code.replace(helper, "(s) => [...s].length")}\n`,
);
